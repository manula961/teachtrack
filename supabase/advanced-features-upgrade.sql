create table if not exists public.departments(
 id bigint generated by default as identity primary key,
 name text not null unique,
 head_teacher_id bigint references public.teachers(id) on delete set null,
 description text not null default '',
 created_at timestamptz not null default now()
);
create table if not exists public.school_org_units(
 id bigint generated by default as identity primary key,
 name text not null,
 unit_type text not null check(unit_type in ('School','Section','Grade','Department')),
 parent_id bigint references public.school_org_units(id) on delete cascade,
 leader_teacher_id bigint references public.teachers(id) on delete set null,
 created_at timestamptz not null default now()
);
create table if not exists public.teacher_service_history(
 id bigint generated by default as identity primary key,
 teacher_id bigint not null references public.teachers(id) on delete cascade,
 event_type text not null check(event_type in ('Appointment','Promotion','Transfer','Service Grade','Responsibility','Other')),
 title text not null,
 institution text not null default '',
 effective_date date not null,
 notes text not null default '',
 created_at timestamptz not null default now()
);
create table if not exists public.duty_roster(
 id bigint generated by default as identity primary key,
 teacher_id bigint not null references public.teachers(id) on delete cascade,
 duty_date date not null,
 duty_type text not null,
 location text not null default '',
 start_time time,
 end_time time,
 status text not null default 'Assigned' check(status in ('Assigned','Completed','Cancelled')),
 notes text not null default '',
 created_at timestamptz not null default now()
);
create table if not exists public.staff_meetings(
 id bigint generated by default as identity primary key,
 title text not null,
 meeting_at timestamptz not null,
 location text not null default '',
 minutes text not null default '',
 created_by uuid default auth.uid() references auth.users(id) on delete set null,
 created_at timestamptz not null default now()
);
alter table public.staff_meetings add column if not exists attendees text not null default '';
create table if not exists public.meeting_actions(
 id bigint generated by default as identity primary key,
 meeting_id bigint references public.staff_meetings(id) on delete cascade,
 teacher_id bigint references public.teachers(id) on delete set null,
 action text not null,
 due_date date,
 status text not null default 'Open' check(status in ('Open','In Progress','Done')),
 created_at timestamptz not null default now()
);
create table if not exists public.qr_attendance_sessions(
 id bigint generated by default as identity primary key,
 session_date date not null default current_date,
 code text not null unique,
 opens_at timestamptz not null default now(),
 closes_at timestamptz not null,
 created_by uuid default auth.uid() references auth.users(id) on delete set null,
 active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.qr_attendance_checkins(
 id bigint generated by default as identity primary key,
 session_id bigint not null references public.qr_attendance_sessions(id) on delete cascade,
 teacher_id bigint not null references public.teachers(id) on delete cascade,
 checked_in_at timestamptz not null default now(),
 unique(session_id,teacher_id)
);
create table if not exists public.school_archives(
 id bigint generated by default as identity primary key,
 academic_year int not null unique,
 title text not null,
 closed_at timestamptz not null default now(),
 summary jsonb not null default '{}'::jsonb,
 created_by uuid default auth.uid() references auth.users(id) on delete set null
);

