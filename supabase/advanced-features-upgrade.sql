alter table public.school_archives enable row level security;

do $$
declare t text;
begin
  foreach t in array array['departments','school_org_units','staff_meetings','meeting_actions','school_archives']
  loop
    execute format('drop policy if exists "%s read" on public.%I',t,t);
    execute format('create policy "%s read" on public.%I for select to authenticated using(true)',t,t);
    execute format('drop policy if exists "%s leadership write" on public.%I',t,t);
    execute format('create policy "%s leadership write" on public.%I for all to authenticated using(public.is_manager()) with check(public.is_manager())',t,t);
  end loop;
end $$;

drop policy if exists "service own or leadership read" on public.teacher_service_history;
create policy "service own or leadership read" on public.teacher_service_history for select to authenticated using(public.is_manager() or teacher_id=public.my_teacher_id());
drop policy if exists "service leadership write" on public.teacher_service_history;
create policy "service leadership write" on public.teacher_service_history for all to authenticated using(public.is_manager()) with check(public.is_manager());

drop policy if exists "duty own or leadership read" on public.duty_roster;
create policy "duty own or leadership read" on public.duty_roster for select to authenticated using(public.is_manager() or teacher_id=public.my_teacher_id());
drop policy if exists "duty leadership write" on public.duty_roster;
create policy "duty leadership write" on public.duty_roster for all to authenticated using(public.is_manager()) with check(public.is_manager());

drop policy if exists "qr sessions read" on public.qr_attendance_sessions;
create policy "qr sessions read" on public.qr_attendance_sessions for select to authenticated using(true);
drop policy if exists "qr sessions leadership write" on public.qr_attendance_sessions;
create policy "qr sessions leadership write" on public.qr_attendance_sessions for all to authenticated using(public.is_manager()) with check(public.is_manager());

drop policy if exists "qr checkins read" on public.qr_attendance_checkins;
create policy "qr checkins read" on public.qr_attendance_checkins for select to authenticated using(public.is_manager() or teacher_id=public.my_teacher_id());
drop policy if exists "qr checkins own insert" on public.qr_attendance_checkins;
create policy "qr checkins own insert" on public.qr_attendance_checkins for insert to authenticated with check(teacher_id=public.my_teacher_id() or public.is_manager());

