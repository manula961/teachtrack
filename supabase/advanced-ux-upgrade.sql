using(user_id=auth.uid()) with check(user_id=auth.uid());

drop policy if exists school_goals_read on public.school_goals;
create policy school_goals_read on public.school_goals for select to authenticated using(true);
drop policy if exists school_goals_manage on public.school_goals;
create policy school_goals_manage on public.school_goals for all to authenticated
using(public.has_role(array['principal','vice_principal','section_head']))
with check(public.has_role(array['principal','vice_principal','section_head']));

drop policy if exists mentoring_pairs_read on public.mentoring_pairs;
create policy mentoring_pairs_read on public.mentoring_pairs for select to authenticated using (
  public.can_review() or mentor_teacher_id=(select teacher_id from public.profiles where id=auth.uid())
  or mentee_teacher_id=(select teacher_id from public.profiles where id=auth.uid())
);
drop policy if exists mentoring_pairs_manage on public.mentoring_pairs;
create policy mentoring_pairs_manage on public.mentoring_pairs for all to authenticated
using(public.can_review()) with check(public.can_review());

drop policy if exists mentoring_sessions_read on public.mentoring_sessions;
create policy mentoring_sessions_read on public.mentoring_sessions for select to authenticated using (
  public.can_review() or exists(
    select 1 from public.mentoring_pairs p
    where p.id=pair_id and (
      p.mentor_teacher_id=(select teacher_id from public.profiles where id=auth.uid())
      or p.mentee_teacher_id=(select teacher_id from public.profiles where id=auth.uid())
    )
  )
);
drop policy if exists mentoring_sessions_write on public.mentoring_sessions;
create policy mentoring_sessions_write on public.mentoring_sessions for all to authenticated using (
  public.can_review() or exists(
    select 1 from public.mentoring_pairs p
    where p.id=pair_id and p.mentor_teacher_id=(select teacher_id from public.profiles where id=auth.uid())
  )
) with check (
  public.can_review() or exists(
    select 1 from public.mentoring_pairs p
    where p.id=pair_id and p.mentor_teacher_id=(select teacher_id from public.profiles where id=auth.uid())
  )
);

