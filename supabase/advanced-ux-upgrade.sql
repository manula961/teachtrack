-- Run after the existing TeachTrack upgrade chain. Designed to be rerunnable.

create table if not exists public.goal_checkins (
  id bigint generated by default as identity primary key,
  goal_id bigint not null references public.goals(id) on delete cascade,
  teacher_id bigint not null references public.teachers(id) on delete cascade,
  progress int not null default 0 check(progress between 0 and 100),
  note text not null default '',
  evidence_url text,
  checkin_date date not null default current_date,
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.evidence_attachments (
  id bigint generated by default as identity primary key,
  teacher_id bigint references public.teachers(id) on delete cascade,
  entity_type text not null,
  entity_id bigint,
  title text not null,
  storage_path text not null,
  storage_provider text not null default 'supabase' check(storage_provider in ('supabase','google_drive')),
  drive_file_id text,
  drive_name text,
  file_type text not null default '',
  notes text not null default '',
  uploaded_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.notification_reads (
  id bigint generated by default as identity primary key,
  notification_id bigint not null references public.notifications(id) on delete cascade,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  read_at timestamptz not null default now(),
  unique(notification_id,user_id)
);

create table if not exists public.notification_preferences (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade unique,
  training boolean not null default true,
  observations boolean not null default true,
  goals boolean not null default true,
  timetable boolean not null default true,
  achievements boolean not null default true,
  general boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.school_goals (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'School Improvement',
  description text not null default '',
  target_value numeric not null default 100,
  current_value numeric not null default 0,
  unit text not null default '%',
  due_date date,
  status text not null default 'Active' check(status in ('Active','On Track','At Risk','Completed')),
  owner_teacher_id bigint references public.teachers(id) on delete set null,
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.mentoring_pairs (
  id bigint generated by default as identity primary key,
  mentor_teacher_id bigint not null references public.teachers(id) on delete cascade,
  mentee_teacher_id bigint not null references public.teachers(id) on delete cascade,
  focus_area text not null default '',
  start_date date not null default current_date,
  end_date date,
  status text not null default 'Active' check(status in ('Active','Completed','Paused')),
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  check(mentor_teacher_id <> mentee_teacher_id)
);

create table if not exists public.mentoring_sessions (
  id bigint generated by default as identity primary key,
  pair_id bigint not null references public.mentoring_pairs(id) on delete cascade,
  session_date date not null default current_date,
  objective text not null,
  notes text not null default '',
  next_step text not null default '',
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.teacher_skill_evidence (
  id bigint generated by default as identity primary key,
  teacher_id bigint not null references public.teachers(id) on delete cascade,
  skill text not null,
  level int not null default 3 check(level between 1 and 5),
  evidence text not null default '',
  reviewed_by uuid default auth.uid() references auth.users(id) on delete set null,
  reviewed_at date not null default current_date,
  unique(teacher_id,skill)
);

create table if not exists public.observation_followups (
  id bigint generated by default as identity primary key,
  observation_id bigint not null references public.observations(id) on delete cascade,
  teacher_id bigint not null references public.teachers(id) on delete cascade,
  recommendation text not null,
  acknowledged boolean not null default false,
  linked_goal_id bigint references public.goals(id) on delete set null,
  followup_date date,
  outcome text not null default '',
  status text not null default 'Open' check(status in ('Open','Acknowledged','Goal Created','Reviewed','Closed')),
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.saved_report_presets (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null,
  configuration jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique(user_id,name)
);

