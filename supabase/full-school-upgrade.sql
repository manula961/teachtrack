-- Automatic notifications for leave decisions.
create or replace function public.notify_leave_decision()
returns trigger language plpgsql security definer set search_path=public as $$
begin
  if new.status is distinct from old.status and new.status in ('Approved','Rejected') then
    insert into public.notifications(recipient_user_id,title,message,category,priority,action_url)
    values(new.requested_by,'Leave request '||lower(new.status),
      'Your '||new.leave_type||' leave request from '||new.start_date||' to '||new.end_date||' was '||lower(new.status)||'.',
      'Leave',case when new.status='Rejected' then 'High' else 'Normal' end,'/leave');
  end if;
  return new;
end; $$;
drop trigger if exists leave_decision_notification on public.leave_requests;
create trigger leave_decision_notification after update on public.leave_requests
for each row execute function public.notify_leave_decision();
