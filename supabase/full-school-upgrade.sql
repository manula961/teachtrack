create policy "leave own or leadership read" on public.leave_requests for select to authenticated
using(public.is_manager() or teacher_id=public.my_teacher_id());
drop policy if exists "leave own create" on public.leave_requests;
create policy "leave own create" on public.leave_requests for insert to authenticated
with check(teacher_id=public.my_teacher_id() or public.is_manager());
