create table if not exists public.academic_terms(
  id bigint generated by default as identity primary key,
  academic_year int not null,
  name text not null,
  start_date date not null,
  end_date date not null,
  status text not null default 'Upcoming' check(status in ('Upcoming','Active','Closed')),
  created_at timestamptz not null default now(),
  unique(academic_year,name)
);

create table if not exists public.leave_requests(
  id bigint generated by default as identity primary key,
  teacher_id bigint not null references public.teachers(id) on delete cascade,
  requested_by uuid not null default auth.uid() references auth.users(id) on delete cascade,
  leave_type text not null check(leave_type in ('Casual','Medical','Duty','Personal','Other')),
  start_date date not null,
  end_date date not null,
  reason text not null default '',
  status text not null default 'Pending' check(status in ('Pending','Approved','Rejected','Cancelled')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  check(end_date>=start_date)
);

create table if not exists public.school_events(
  id bigint generated by default as identity primary key,
  title text not null,
  event_type text not null default 'School Event',
  start_at timestamptz not null,
  end_at timestamptz,
  audience text not null default 'All Staff',
  location text not null default '',
  notes text not null default '',
  created_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.exam_responsibilities(
  id bigint generated by default as identity primary key,
  teacher_id bigint not null references public.teachers(id) on delete cascade,
  exam_name text not null,
  responsibility text not null check(responsibility in ('Paper Setting','Moderation','Invigilation','Marking','Results','Other')),
  subject text not null default '',
  grade text not null default '',
  due_date date,
  status text not null default 'Assigned' check(status in ('Assigned','In Progress','Completed')),
  notes text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.teacher_documents(
  id bigint generated by default as identity primary key,
  teacher_id bigint not null references public.teachers(id) on delete cascade,
  title text not null,
  document_type text not null default 'Other',
  storage_path text not null,
  expiry_date date,
  uploaded_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.development_plans(
  id bigint generated by default as identity primary key,
  teacher_id bigint not null references public.teachers(id) on delete cascade,
  title text not null,
  focus_area text not null,
  action_steps text not null default '',
  target_date date,
  progress int not null default 0 check(progress between 0 and 100),
  status text not null default 'Active' check(status in ('Active','On Track','At Risk','Completed')),
  assigned_by uuid default auth.uid() references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.observation_rubrics(
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text not null default '',
  max_score int not null default 5 check(max_score between 1 and 10),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.observation_scores(
  id bigint generated by default as identity primary key,
  observation_id bigint references public.observations(id) on delete cascade,
  rubric_id bigint not null references public.observation_rubrics(id) on delete cascade,
  score numeric(5,2) not null,
  note text not null default '',
  created_at timestamptz not null default now(),
  unique(observation_id,rubric_id)
);

create table if not exists public.notifications(
  id bigint generated by default as identity primary key,
  recipient_user_id uuid references auth.users(id) on delete cascade,
  title text not null,
  message text not null,
  category text not null default 'General',
  priority text not null default 'Normal' check(priority in ('Normal','High')),
  read_at timestamptz,
  action_url text,
  created_at timestamptz not null default now()
);

