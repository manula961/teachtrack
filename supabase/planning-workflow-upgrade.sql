drop policy if exists "requirements read" on public.class_subject_requirements;
create policy "requirements read" on public.class_subject_requirements for select to authenticated using(true);
drop policy if exists "requirements leadership write" on public.class_subject_requirements;
create policy "requirements leadership write" on public.class_subject_requirements for all to authenticated
using(public.is_manager()) with check(public.is_manager());

drop policy if exists "workflows read" on public.approval_workflows;
create policy "workflows read" on public.approval_workflows for select to authenticated using(true);
drop policy if exists "workflows leadership write" on public.approval_workflows;
create policy "workflows leadership write" on public.approval_workflows for all to authenticated
using(public.is_manager()) with check(public.is_manager());

drop policy if exists "approval requests read" on public.approval_requests;
create policy "approval requests read" on public.approval_requests for select to authenticated
using(requested_by=auth.uid() or public.can_review());
drop policy if exists "approval requests create" on public.approval_requests;
create policy "approval requests create" on public.approval_requests for insert to authenticated
with check(requested_by=auth.uid());
drop policy if exists "approval requests reviewers update" on public.approval_requests;
create policy "approval requests reviewers update" on public.approval_requests for update to authenticated
using(public.can_review()) with check(public.can_review());

drop policy if exists "approval actions read" on public.approval_actions;
create policy "approval actions read" on public.approval_actions for select to authenticated
using(public.can_review() or exists(select 1 from public.approval_requests r where r.id=request_id and r.requested_by=auth.uid()));
drop policy if exists "approval actions review insert" on public.approval_actions;
create policy "approval actions review insert" on public.approval_actions for insert to authenticated
with check(public.can_review());

drop policy if exists "promotion read" on public.school_year_promotions;
