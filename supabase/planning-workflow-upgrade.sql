create table if not exists public.class_subject_requirements(
 id bigint generated by default as identity primary key,
 class_id bigint not null references public.timetable_classes(id) on delete cascade,
 teacher_id bigint not null references public.teachers(id) on delete cascade,
 subject text not null,
 periods_per_week int not null default 5 check(periods_per_week between 1 and 20),
 room text not null default '',
 priority int not null default 1 check(priority between 1 and 5),
 created_at timestamptz not null default now(),
 unique(class_id,subject)
);

create table if not exists public.approval_workflows(
 id bigint generated by default as identity primary key,
 name text not null unique,
 entity_type text not null,
 steps jsonb not null default '["section_head","vice_principal","principal"]'::jsonb,
 active boolean not null default true,
 created_at timestamptz not null default now()
);

create table if not exists public.approval_requests(
 id bigint generated by default as identity primary key,
 workflow_id bigint not null references public.approval_workflows(id) on delete cascade,
 entity_type text not null,
 entity_id bigint,
 title text not null,
 description text not null default '',
 requested_by uuid not null default auth.uid() references auth.users(id) on delete cascade,
 current_step int not null default 0,
 status text not null default 'Pending' check(status in ('Pending','Approved','Rejected','Cancelled')),
 created_at timestamptz not null default now(),
 completed_at timestamptz
);

create table if not exists public.approval_actions(
 id bigint generated by default as identity primary key,
 request_id bigint not null references public.approval_requests(id) on delete cascade,
 actor_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
 actor_role text not null,
 action text not null check(action in ('Approved','Rejected','Commented')),
 comment text not null default '',
 created_at timestamptz not null default now()
);

create table if not exists public.school_year_promotions(
 id bigint generated by default as identity primary key,
 from_year int not null,
 to_year int not null,
 source_class_id bigint references public.timetable_classes(id) on delete set null,
 target_class_id bigint references public.timetable_classes(id) on delete set null,
 source_class_name text not null,
 target_class_name text not null,
 status text not null default 'Completed',
 promoted_by uuid default auth.uid() references auth.users(id) on delete set null,
 created_at timestamptz not null default now()
);

