-- Derived performance metrics are calculated by PostgreSQL views.
create or replace view public.teacher_metrics with (security_invoker=true) as
select t.id,
  coalesce((select round(100.0 * count(*) filter (where a.status in ('Present','Late')) / nullif(count(*),0),1) from public.attendance a where a.teacher_id=t.id),100) as attendance_score,
  coalesce((select round(avg(f.rating)::numeric,1) from public.feedback f where f.teacher_id=t.id),0) as feedback_score,
  coalesce((select sum(tr.hours) from public.training tr where tr.teacher_id=t.id and tr.status='Completed'),0) as training_hours,
  (select count(*) from public.lessons l where l.teacher_id=t.id) as lesson_count
from public.teachers t;

create or replace view public.teachers_dashboard with (security_invoker=true) as
select t.*,
  m.attendance_score,m.feedback_score,m.training_hours,m.lesson_count,
  round((m.attendance_score * .45 + (m.feedback_score/5*100) * .35 + least(m.training_hours,40)/40*100 * .20)::numeric,1) as performance_score
from public.teachers t join public.teacher_metrics m on m.id=t.id;

-- New Auth users automatically receive a safe teacher role profile.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path=public as $$
begin
  insert into public.profiles(id,full_name,role)
  values(new.id,coalesce(new.raw_user_meta_data->>'full_name',''),'teacher')
  on conflict (id) do nothing;
  return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.current_role() returns public.app_role
language sql stable security definer set search_path=public as $$
  select role from public.profiles where id=auth.uid();
$$;

create or replace function public.has_role(allowed public.app_role[]) returns boolean
language sql stable security definer set search_path=public as $$
  select exists(
    select 1 from public.profiles p
    where p.id=auth.uid() and p.role = any(allowed)
  );
$$;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path=public as $$
  select public.has_role(array['principal']::public.app_role[]);
$$;

create or replace function public.is_manager() returns boolean
language sql stable security definer set search_path=public as $$
  select public.has_role(array['principal','vice_principal']::public.app_role[]);
$$;

create or replace function public.can_review() returns boolean
language sql stable security definer set search_path=public as $$
  select public.has_role(array['principal','vice_principal','section_head','reviewer']::public.app_role[]);
$$;

create or replace function public.my_teacher_id() returns bigint
language sql stable security definer set search_path=public as $$
  select teacher_id from public.profiles where id=auth.uid();
$$;


-- User-control RPC. Authenticated leadership can change application roles without
-- exposing auth.users or allowing direct profile-role edits.
create or replace function public.set_user_role(target_user uuid, new_role public.app_role)
returns void
language plpgsql
security definer
set search_path=public
as $$
declare
  caller_role public.app_role;
begin
  select role into caller_role from public.profiles where id=auth.uid();

  if caller_role='principal' then
    if new_role not in ('principal','vice_principal','section_head','reviewer','teacher') then
      raise exception 'Role not allowed';
    end if;
  elsif caller_role='vice_principal' then
    if new_role not in ('section_head','reviewer','teacher') then
      raise exception 'Vice Principal cannot assign this role';
    end if;
    if exists(select 1 from public.profiles where id=target_user and role in ('principal','vice_principal')) then
      raise exception 'Vice Principal cannot modify Principal or Vice Principal accounts';
    end if;
  else
    raise exception 'Not authorized';
  end if;

  if target_user=auth.uid() then
    raise exception 'You cannot change your own role';
  end if;

  update public.profiles set role=new_role where id=target_user;
  if not found then raise exception 'User profile not found'; end if;

  insert into public.activity_logs(actor_id,actor_name,action,entity_type,metadata)
  select auth.uid(),coalesce(p.full_name,'Leadership user'),'Changed user role','profile',
         jsonb_build_object('target_user',target_user,'new_role',new_role::text)
  from public.profiles p where p.id=auth.uid();
end;
$$;

grant execute on function public.set_user_role(uuid, public.app_role) to authenticated;

