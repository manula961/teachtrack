-- Database-level clash protection.
create or replace function public.check_timetable_clash()
returns trigger
language plpgsql
set search_path=public
as $$
declare
  p_interval boolean;
begin
  select is_interval into p_interval from public.school_periods where id=new.period_id;
  if p_interval then
    raise exception 'Lessons cannot be assigned during the interval';
  end if;

  if exists(
    select 1 from public.timetable_entries e
    where e.teacher_id=new.teacher_id
      and e.day_of_week=new.day_of_week
      and e.period_id=new.period_id
      and e.id<>coalesce(new.id,0)
  ) then
    raise exception 'Teacher clash: this teacher already has a lesson in that period';
  end if;

  if nullif(trim(new.room),'') is not null and exists(
    select 1 from public.timetable_entries e
    where lower(trim(e.room))=lower(trim(new.room))
      and e.day_of_week=new.day_of_week
      and e.period_id=new.period_id
      and e.id<>coalesce(new.id,0)
  ) then
    raise exception 'Room clash: this room is already occupied in that period';
  end if;

  return new;
end;
$$;

drop trigger if exists timetable_clash_guard on public.timetable_entries;
create trigger timetable_clash_guard
before insert or update on public.timetable_entries
for each row execute function public.check_timetable_clash();

create or replace function public.check_substitute_clash()
returns trigger
language plpgsql
set search_path=public
as $$
declare
  v_day smallint;
  v_period smallint;
begin
  v_day := extract(isodow from new.date)::smallint;
  select period_id into v_period from public.timetable_entries where id=new.timetable_entry_id;

  if v_day between 1 and 5 and exists(
    select 1 from public.timetable_entries e
    where e.teacher_id=new.substitute_teacher_id
      and e.day_of_week=v_day
      and e.period_id=v_period
  ) then
    raise exception 'Substitute clash: this teacher already teaches during that period';
  end if;

  return new;
end;
$$;

drop trigger if exists substitute_clash_guard on public.timetable_substitutions;
create trigger substitute_clash_guard
before insert or update on public.timetable_substitutions
for each row execute function public.check_substitute_clash();

